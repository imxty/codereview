package main

import (
	"flag"
	"log"
	"os"
	"text/template"

	plugins "github.com/jinmukeji/huimaibao-service/svc/summary"
	"gopkg.in/yaml.v2"
)

var (
	cfgFile, outFile, pkgName string
)

func main() {
	flag.StringVar(&cfgFile, "c", "errors.yml", "The error configuration file used to generate go file.")
	flag.StringVar(&outFile, "o", "error.gen.go", "The output go filepath.")
	flag.StringVar(&pkgName, "p", "example", "The go package name.")
	flag.Parse()

	// 读取 error 配置文件
	data, _ := os.ReadFile(cfgFile)
	var doc riskDoc
	doc.PkgName = pkgName
	err := yaml.Unmarshal(data, &(doc.Risks))
	die(err)

	// 写入目标 go 文件
	f, err := os.Create(outFile)
	die(err)
	defer f.Close()

	err = errorTemplate.Execute(f, doc)
	die(err)
}

func die(err error) {
	if err != nil {
		log.Fatal(err)
	}
}

type riskDoc struct {
	PkgName string
	Risks   map[string]plugins.Risk
}

var errorTemplate = template.Must(template.New("").Parse(`// Code generated by go generate. DO NOT EDIT.

package {{.PkgName}}

var (
    // 疾病映射
    RiskMap = map[string]Risk{
		{{- range $k,$risk := .Risks}}
		{{$risk.CommentLine}}
        {{$k | printf "%q"}}:{
            Label: {{$risk.Label | printf "%q"}},
        },
        {{- end }}
    }
)

`))
